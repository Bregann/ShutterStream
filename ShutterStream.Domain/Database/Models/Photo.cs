using Microsoft.EntityFrameworkCore;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace ShutterStream.Domain.Database.Models
{
    [Index(nameof(AlbumId), nameof(SubFolder), nameof(FileName), IsUnique = true)]
    public class Photo
    {
        [Key, DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public int Id { get; set; }

        [Required]
        public required int AlbumId { get; set; }

        [ForeignKey(nameof(AlbumId))]
        [DeleteBehavior(DeleteBehavior.Cascade)]
        public virtual Album Album { get; set; } = null!;

        /// <summary>
        /// Path of the folder the photo is in, relative to the album folder and separated by "/",
        /// e.g. "Day 1" for a holiday split by day. Empty when the photo sits directly in the album folder.
        /// The album page shows a section per sub folder.
        /// </summary>
        [Required]
        public string SubFolder { get; set; } = "";

        [Required]
        public required string FileName { get; set; }

        /// <summary>
        /// File size and modified time are used by the scanner to detect changed files.
        /// </summary>
        [Required]
        public required long FileSizeBytes { get; set; }

        [Required]
        public required DateTime FileModifiedAt { get; set; }

        /// <summary>
        /// Dimensions after the EXIF orientation has been applied, i.e. how the photo is displayed.
        /// </summary>
        [Required]
        public required int Width { get; set; }

        [Required]
        public required int Height { get; set; }

        /// <summary>
        /// The EXIF DateTimeOriginal. Cameras record this as wall clock time with no timezone,
        /// so it is stored as UTC purely to satisfy Postgres and must be displayed without conversion.
        /// </summary>
        public DateTime? DateTaken { get; set; }

        public string? CameraMake { get; set; }

        public string? CameraModel { get; set; }

        public string? LensModel { get; set; }

        public double? FocalLength { get; set; }

        public double? Aperture { get; set; }

        public string? ExposureTime { get; set; }

        public int? Iso { get; set; }

        /// <summary>
        /// Generated by AI from the photo, and editable from the admin interface.
        /// </summary>
        public string? Title { get; set; }

        public string? Description { get; set; }

        /// <summary>
        /// When the AI last captioned this photo. Cleared when the admin edits the caption by hand,
        /// so a later "regenerate" run never overwrites hand written captions.
        /// </summary>
        public DateTime? CaptionGeneratedAt { get; set; }

        /// <summary>
        /// Lets the admin hide individual photos inside a public album.
        /// </summary>
        [Required]
        public bool IsHidden { get; set; } = false;

        [Required]
        public bool ThumbnailsGenerated { get; set; } = false;

        /// <summary>
        /// Times the photo has been opened by a visitor. The admin's own views are not counted.
        /// </summary>
        [Required]
        public int ViewCount { get; set; } = 0;

        [Required]
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    }
}
